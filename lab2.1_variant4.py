from math import *

x = float(input('Введите значение x='))

if x < 0:
    # Прямая от -10 до 0 (и автоматически продолжается влево)
    y = -3 - 0.5 * x
elif x < 3:
    # Четверть окружности (центр 0,0, радиус 3) от 0 до 3
    y = -sqrt(9 - x**2)
elif x <= 6:
    # Четверть окружности (центр 6,0, радиус 3) от 3 до 6
    y = sqrt(9 - (x - 6)**2)
else:
    # Горизонтальная линия после x = 6 (продолжается вправо)
    y = 3

print("X={0:.2f} Y={1:.2f}".format(x, y))